export function formatNaira(amount: number): string {
  return '₦' + Math.round(amount).toLocaleString('en-NG');
}

export function formatDateHuman(dateStr: string): string {
  if (!dateStr) return '—';
  const parsed = new Date(dateStr);
  if (isNaN(parsed.getTime())) return dateStr;
  return parsed.toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
}

export function daysUntilDate(dateStr: string): { label: string; isUrgent: boolean; isPast: boolean } {
  const refNow = new Date('2026-11-10T11:00:00');
  const target = new Date(dateStr);
  if (isNaN(target.getTime())) {
    return { label: dateStr, isUrgent: false, isPast: false };
  }
  const diffDays = Math.ceil((target.getTime() - refNow.getTime()) / (1000 * 60 * 60 * 24));
  if (diffDays <= 0) {
    return { label: 'Ready Today', isUrgent: true, isPast: false };
  }
  if (diffDays === 1) {
    return { label: 'Harvests Tomorrow', isUrgent: true, isPast: false };
  }
  if (diffDays <= 5) {
    return { label: `Harvests in ${diffDays} days`, isUrgent: true, isPast: false };
  }
  return { label: `Harvests in ${diffDays} days`, isUrgent: false, isPast: false };
}
